export const teamName = (code, lang = 'fr') => TEAMS[code]?.[lang] || TEAMS[code]?.fr || code
export const teamElo = (code) => TEAMS[code]?.elo || 1500

export function Flag({ code, size = 32, rounded = true }) {
  const iso = TEAMS[code]?.iso
  if (!iso) {
    return (
      <span style={{
        display: 'inline-block', width: size, height: Math.round(size * 0.66),
        background: 'rgba(255,255,255,0.1)', borderRadius: rounded ? 3 : 0,
        textAlign: 'center', fontSize: 10, lineHeight: `${Math.round(size * 0.66)}px`,
      }}>{code}</span>
    )
  }
  const w = size <= 20 ? 'w20' : size <= 40 ? 'w40' : size <= 80 ? 'w80' : 'w160'
  const w2x = size <= 20 ? 'w40' : size <= 40 ? 'w80' : size <= 80 ? 'w160' : 'w320'
  return (
    <img
      src={`https://flagcdn.com/${w}/${iso}.png`}
      srcSet={`https://flagcdn.com/${w}/${iso}.png 1x, https://flagcdn.com/${w2x}/${iso}.png 2x`}
      width={size}
      height={Math.round(size * 0.66)}
      alt={teamName(code)}
      style={{ display: 'inline-block', objectFit: 'cover', borderRadius: rounded ? 3 : 0, verticalAlign: 'middle' }}
      loading="lazy"
    />
  )
}
