const I18nContext = createContext({ lang: 'fr', t: (k) => k, setLang: () => {} })

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem('prono26_lang')
    if (saved) return saved
    const navLang = navigator.language?.toLowerCase() || ''
    if (navLang.startsWith('es')) return 'es'
    if (navLang.startsWith('en')) return 'en'
    return 'fr'
  })

  useEffect(() => {
    localStorage.setItem('prono26_lang', lang)
    document.documentElement.lang = lang
  }, [lang])

  const setLang = (newLang) => setLangState(newLang)
  const t = (key, fallback) => TRANSLATIONS[lang]?.[key] || TRANSLATIONS['fr']?.[key] || fallback || key

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export const useTranslation = () => useContext(I18nContext)
